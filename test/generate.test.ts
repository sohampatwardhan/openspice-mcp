import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { readAsc } from "../src/asc.js";
import { toNetlist } from "../src/ascnet.js";
import { generateAsc, type Circuit } from "../src/generate.js";
import { SymbolResolver } from "../src/symbols.js";

const resolver = new SymbolResolver([]);

/** An RC low-pass: V1 drives `in`, R1 from `in` to `out`, C1 from `out` to ground. */
const RC_LOWPASS: Circuit = {
  title: "RC low-pass",
  devices: [
    { kind: "V", name: "V1", nodes: ["in", "0"], value: "AC 1" },
    { kind: "R", name: "R1", nodes: ["in", "out"], value: "1k" },
    { kind: "C", name: "C1", nodes: ["out", "0"], value: "159n" },
  ],
  directives: [".ac dec 20 1 1meg"],
};

describe("generateAsc", () => {
  it("rejects an inconsistent circuit with GENERATE_INVALID", async () => {
    await assert.rejects(
      generateAsc({ title: "bad", devices: [{ kind: "R", name: "R1", nodes: ["a"], value: "1k" }], directives: [] }),
      (err: unknown) => (err as { code?: string }).code === "GENERATE_INVALID",
    );
  });

  it("rejects a duplicate instance name with GENERATE_INVALID", async () => {
    await assert.rejects(
      generateAsc({
        title: "dup",
        devices: [
          { kind: "R", name: "R1", nodes: ["a", "0"], value: "1k" },
          { kind: "R", name: "R1", nodes: ["a", "0"], value: "2k" },
        ],
        directives: [],
      }),
      (err: unknown) => (err as { code?: string }).code === "GENERATE_INVALID",
    );
  });

  it("produces LTspice-openable .asc bytes with CRLF and a recorded encoding", async () => {
    const result = await generateAsc(RC_LOWPASS);
    const text = result.bytes.toString("utf8");
    assert.match(text, /^Version 4\r\n/);
    assert.match(text, /\r\nSHEET /);
    assert.match(text, /SYMBOL (res|cap|voltage)/);
    assert.match(text, /SYMATTR InstName R1/);
    assert.match(text, /SYMATTR InstName C1/);
    assert.match(text, /SYMATTR InstName V1/);
    // On-sheet directive text carries the analysis with a leading !.
    assert.match(text, /TEXT .*!\.ac dec 20 1 1meg/);
    assert.equal(result.encoding, "utf-8");
  });

  it("is deterministic: the same circuit yields identical bytes", async () => {
    const a = await generateAsc(RC_LOWPASS);
    const b = await generateAsc(RC_LOWPASS);
    assert.deepEqual(a.bytes, b.bytes);
  });

  it("round-trips to the intended connectivity through the real converter", async () => {
    const result = await generateAsc(RC_LOWPASS);
    assert.equal(result.verified, true);
    assert.equal(result.diffs.length, 0);

    // Independently re-run the real converter on the generated bytes.
    const schematic = readAsc(result.bytes);
    const converted = await toNetlist(schematic, resolver);
    const r1 = converted.netlist.devices.find((d) => d.name === "R1");
    const c1 = converted.netlist.devices.find((d) => d.name === "C1");
    const v1 = converted.netlist.devices.find((d) => d.name === "V1");
    assert.deepEqual(r1?.nodes, ["in", "out"]);
    assert.deepEqual(c1?.nodes, ["out", "0"]);
    assert.deepEqual(v1?.nodes, ["in", "0"]);
  });

  it("emits an equivalent netlist alongside the schematic", async () => {
    const result = await generateAsc(RC_LOWPASS);
    assert.match(result.netlistText, /R1 in out 1k/);
    assert.match(result.netlistText, /C1 out 0 159n/);
    assert.match(result.netlistText, /V1 in 0 AC 1/);
    assert.match(result.netlistText, /\.ac dec 20 1 1meg/);
  });

  it("reports verified false with diffs when connectivity cannot be matched", async () => {
    // A device whose symbol is unknown cannot be netlisted back, so the round
    // trip cannot confirm its connectivity.
    const result = await generateAsc(
      {
        title: "opaque",
        devices: [{ kind: "X", name: "X1", nodes: ["a", "0"], model: "myblock" }],
        directives: [],
      },
      { strict: false },
    );
    assert.equal(result.verified, false);
    assert.ok(result.diffs.length > 0);
  });

  it("throws GENERATE_UNVERIFIED in strict mode when the round trip mismatches", async () => {
    await assert.rejects(
      generateAsc(
        {
          title: "opaque",
          devices: [{ kind: "X", name: "X1", nodes: ["a", "0"], model: "myblock" }],
          directives: [],
        },
        { strict: true },
      ),
      (err: unknown) => (err as { code?: string }).code === "GENERATE_UNVERIFIED",
    );
  });
});
